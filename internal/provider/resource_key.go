var (
	_ resource.Resource                = (*keyResource)(nil)
	_ resource.ResourceWithImportState = (*keyResource)(nil)
)

type keyResource struct {
	client *client.Client
}

type keyModel struct {
	ID                types.String      `tfsdk:"id"`
	Name              types.String      `tfsdk:"name"`
	SecretAccessKey   types.String      `tfsdk:"secret_access_key"`
	Expiration        timetypes.RFC3339 `tfsdk:"expiration"`
	AllowCreateBucket types.Bool        `tfsdk:"allow_create_bucket"`
	Created           types.String      `tfsdk:"created"`
	Expired           types.Bool        `tfsdk:"expired"`
}

func newKeyResource() resource.Resource {
	return &keyResource{}
}

func (r *keyResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_key"
}

func (r *keyResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.client = clientFromResource(req, resp)
}

func (r *keyResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "An S3 access key. Grant it access to buckets with `garage_bucket_permission`.\n\n" +
			"Set `id` and `secret_access_key` to import credentials that already exist elsewhere, for example from another S3 service. " +
			"Garage never accepts an ID again once its key is deleted, so replacing an imported key needs new credentials.\n\n" +
			"The secret is stored in the state.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Optional:            true,
				Computed:            true,
				MarkdownDescription: "Access key ID, starting with `GK`. Generated by Garage unless set together with `secret_access_key`.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown(), stringplanmodifier.RequiresReplace()},
				Validators: []validator.String{
					stringvalidator.AlsoRequires(path.MatchRoot("secret_access_key")),
					stringvalidator.RegexMatches(keyIDRegex, "must be GK followed by 24 hexadecimal characters"),
				},
			},
			"name": schema.StringAttribute{
				Optional:            true,
				Computed:            true,
				MarkdownDescription: "Human-readable name of the key.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"secret_access_key": schema.StringAttribute{
				Optional:            true,
				Computed:            true,
				Sensitive:           true,
				MarkdownDescription: "Secret access key. Generated by Garage unless set together with `id`.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown(), stringplanmodifier.RequiresReplace()},
				Validators: []validator.String{
					stringvalidator.AlsoRequires(path.MatchRoot("id")),
					stringvalidator.RegexMatches(keySecretRegex, "must be 64 hexadecimal characters"),
				},
			},
			"expiration": schema.StringAttribute{
				CustomType:          timetypes.RFC3339Type{},
				Optional:            true,
				MarkdownDescription: "Date after which the key stops working, in RFC 3339 format. Unset means the key never expires.",
			},
			"allow_create_bucket": schema.BoolAttribute{
				Optional:            true,
				Computed:            true,
				Default:             booldefault.StaticBool(false),
				MarkdownDescription: "Allow the key to create buckets through the S3 API.",
			},
			"created": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Creation date of the key.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"expired": schema.BoolAttribute{
				Computed:            true,
				MarkdownDescription: "Whether the key has expired.",
			},
		},
	}
}

func (m *keyModel) updateRequest(prior *keyModel) (client.UpdateKeyRequest, error) {
	req := client.UpdateKeyRequest{Name: stringPtr(m.Name)}
	if m.AllowCreateBucket.ValueBool() {
		req.Allow = &client.KeyPermissions{CreateBucket: true}
	} else {
		req.Deny = &client.KeyPermissions{CreateBucket: true}
	}
	expiration, diags := rfc3339String(m.Expiration)
	if diags.HasError() {
		return req, fmt.Errorf("invalid expiration")
	}
	if expiration != nil {
		req.Expiration = expiration
	} else if prior == nil || !prior.Expiration.IsNull() {
		req.NeverExpires = true
	}
	return req, nil
}

func (m *keyModel) readFrom(k *client.Key) {
	m.ID = types.StringValue(k.AccessKeyID)
	m.Name = types.StringValue(k.Name)
	if k.SecretAccessKey != nil {
		m.SecretAccessKey = types.StringValue(*k.SecretAccessKey)
	}
	m.Expiration = keepEquivalentTime(m.Expiration, rfc3339Value(k.Expiration))
	m.AllowCreateBucket = types.BoolValue(k.Permissions.CreateBucket)
	m.Created = stringValue(k.Created)
	m.Expired = types.BoolValue(k.Expired)
}

func (r *keyResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan keyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var key *client.Key
	var err error
	if !plan.ID.IsUnknown() && !plan.ID.IsNull() {
		key, err = r.client.ImportKey(ctx, client.ImportKeyRequest{
			AccessKeyID:     plan.ID.ValueString(),
			SecretAccessKey: plan.SecretAccessKey.ValueString(),
			Name:            stringPtr(plan.Name),
		})
	} else {
		key, err = r.client.CreateKey(ctx, client.UpdateKeyRequest{Name: stringPtr(plan.Name)})
	}
	if err != nil {
		resp.Diagnostics.AddError("Cannot create the key", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), key.AccessKeyID)...)

	update, err := plan.updateRequest(nil)
	if err != nil {
		resp.Diagnostics.AddError("Invalid key configuration", err.Error())
		return
	}
	if _, err := r.client.UpdateKey(ctx, key.AccessKeyID, update); err != nil {
		resp.Diagnostics.AddError("Cannot configure the key", err.Error())
		return
	}
	r.read(ctx, key.AccessKeyID, &plan, &resp.State, &resp.Diagnostics)
}

func (r *keyResource) read(ctx context.Context, id string, m *keyModel, state stateSetter, diags diagAppender) bool {
	key, err := r.client.GetKey(ctx, id, true)
	if err != nil {
		if client.IsNotFound(err) {
			return false
		}
		diags.AddError("Cannot read the key", err.Error())
		return true
	}
	m.readFrom(key)
	diags.Append(state.Set(ctx, m)...)
	return true
}

func (r *keyResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state keyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if !r.read(ctx, state.ID.ValueString(), &state, &resp.State, &resp.Diagnostics) {
		resp.State.RemoveResource(ctx)
	}
}

func (r *keyResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state keyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	update, err := plan.updateRequest(&state)
	if err != nil {
		resp.Diagnostics.AddError("Invalid key configuration", err.Error())
		return
	}
	if _, err := r.client.UpdateKey(ctx, state.ID.ValueString(), update); err != nil {
		resp.Diagnostics.AddError("Cannot update the key", err.Error())
		return
	}
	r.read(ctx, state.ID.ValueString(), &plan, &resp.State, &resp.Diagnostics)
}

func (r *keyResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state keyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.DeleteKey(ctx, state.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Cannot delete the key", err.Error())
	}
}

func (r *keyResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), req.ID)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("expiration"), timetypes.NewRFC3339Null())...)
}
